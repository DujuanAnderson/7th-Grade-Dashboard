// Minimal inline SVG icon set (stroke-based, 24x24 viewBox) — no emoji, no
// icon-font dependency. Every icon takes the same { size, className } shape
// so call sites can drop them in next to text at any size/color via
// currentColor.
export interface IconProps {
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}

function Svg({ size = 16, className, style, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden
    >
      {children}
    </svg>
  );
}

